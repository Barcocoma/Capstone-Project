/**
 * Resolve lot type for a given garden/sector/block.
 * Defaults to 'standard' if not defined.
 */
function resolve_lot_type(string $garden, string $sector, int $blockNumber): string {
    global $BLOCK_TYPE_MAP;
    $type = 'standard';
    if (isset($BLOCK_TYPE_MAP[$garden][$sector][$blockNumber])) {
        $type = $BLOCK_TYPE_MAP[$garden][$sector][$blockNumber];
    }
    return $type;
}

/**
 * Get generic details for a lot type.
 */
function get_lot_type_details(string $type): array {
    global $LOT_TYPE_DETAILS;
    return $LOT_TYPE_DETAILS[$type] ?? $LOT_TYPE_DETAILS['standard'];
}

